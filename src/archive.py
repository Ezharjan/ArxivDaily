"""Data for the web archive (the GitHub Pages site in web/).

Layout (committed to the repository so the history survives between runs)::

    web/data/index.json             days, topics and site info
    web/data/days/2026-11-13.json   matching papers of one announcement (best first,
                                    up to archive.max_papers_per_day)

The page (web/index.html) reads index.json first and loads day files as the
reader scrolls. Each day entry carries a short content hash (``rev``) that the
page appends to the file URL, so browsers and GitHub's CDN never serve a stale
copy and nobody has to press F5 to see new papers.
"""

from __future__ import annotations

import datetime as _dt
import hashlib
import json
import logging
import os
import shutil
from typing import Dict, Iterable, Optional, Sequence

from . import taxonomy
from .arxiv_fetcher import Paper

log = logging.getLogger(__name__)

DATA_VERSION = 1


def _read_json(path: str) -> Optional[dict]:
    try:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, dict) else None
    except (OSError, ValueError):
        return None


def _write_json(path: str, data: dict) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")
    os.replace(tmp, path)


def _rev(path: str) -> str:
    with open(path, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()[:10]


def belongs_to(data_dir: str, repository: str) -> bool:
    """False when the archive was generated by a different repository (e.g. inherited by a fork)."""
    index = _read_json(os.path.join(data_dir, "index.json")) or {}
    owner = str(index.get("repository") or "")
    return not (repository and owner and owner.lower() != repository.lower())


def update(
    data_dir: str,
    *,
    day: _dt.date,
    papers: Iterable[Paper],
    keywords: Sequence[str],
    categories: Sequence[str] = (),
    repository: str = "",
    keep_days: int = 90,
    max_per_day: int = 200,
    title: str = "ArxivDaily",
) -> bool:
    """Merge ``papers`` into the archive for ``day``. Returns True if any file changed."""
    days_dir = os.path.join(data_dir, "days")
    index_path = os.path.join(data_dir, "index.json")

    if not belongs_to(data_dir, repository):
        log.info("web archive belongs to another repository — starting a fresh archive")
        shutil.rmtree(days_dir, ignore_errors=True)
        try:
            os.remove(index_path)
        except OSError:
            pass

    changed = False
    papers = list(papers)
    if papers:
        day_path = os.path.join(days_dir, f"{day.isoformat()}.json")
        existing = _read_json(day_path) or {}
        by_id: Dict[str, dict] = {p.get("id"): p for p in existing.get("papers", []) if isinstance(p, dict) and p.get("id")}
        for p in papers:
            by_id[p.short_id] = p.to_dict()
        merged = sorted(by_id.values(), key=lambda d: (-float(d.get("score", 0)), str(d.get("id"))))[:max_per_day]
        new_day = {"date": day.isoformat(), "papers": merged}
        if new_day != existing:
            _write_json(day_path, new_day)
            changed = True

    # Prune days that fell out of the retention window.
    cutoff = day - _dt.timedelta(days=keep_days)
    if os.path.isdir(days_dir):
        for name in sorted(os.listdir(days_dir)):
            stem = name[:-5] if name.endswith(".json") else ""
            try:
                file_day = _dt.date.fromisoformat(stem)
            except ValueError:
                continue
            if file_day < cutoff:
                os.remove(os.path.join(days_dir, name))
                changed = True

    # Rebuild the index from the files on disk (the files are the source of truth).
    entries = []
    codes = set(categories)
    if os.path.isdir(days_dir):
        for name in sorted(os.listdir(days_dir), reverse=True):
            if not name.endswith(".json"):
                continue
            path = os.path.join(days_dir, name)
            data = _read_json(path) or {}
            day_papers = data.get("papers") or []
            kw_counts: Dict[str, int] = {}
            for p in day_papers:
                for kw in p.get("kw") or []:
                    kw_counts[kw] = kw_counts.get(kw, 0) + 1
                codes.update(p.get("cats") or [])
            entries.append({"date": name[:-5], "count": len(day_papers), "rev": _rev(path), "kw": kw_counts})

    index = {
        "version": DATA_VERSION,
        "repository": repository,
        "title": title,
        "keywords": list(keywords),
        "categories": list(categories),
        "category_names": {c: taxonomy.category_name(c) for c in sorted(codes) if taxonomy.category_name(c)},
        "days": entries,
    }
    old = _read_json(index_path) or {}
    old_core = {k: v for k, v in old.items() if k != "generated_at"}
    if old_core != index:
        index["generated_at"] = _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0).isoformat()
        _write_json(index_path, index)
        changed = True
    if changed:
        log.info("web archive updated: %d day(s), newest %s", len(entries), entries[0]["date"] if entries else "-")
    return changed


def build_preview_site(web_dir: str, out_dir: str) -> str:
    """Copy the site (web/) into out_dir so a preview never touches the real archive."""
    shutil.rmtree(out_dir, ignore_errors=True)
    shutil.copytree(web_dir, out_dir)
    return out_dir
